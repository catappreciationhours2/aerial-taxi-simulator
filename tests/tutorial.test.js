import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { STEPS, eventAllowed, Tutorial } from '../web/tutorial.js';
import { Engine } from '../src/sim/engine.js';
import { FEATURE_LABELS } from '../src/core/config.js';
import { FAULT_TYPES } from '../src/sim/faults.js';
import { VIEWS } from '../web/render.js';

const html = readFileSync(new URL('../web/index.html', import.meta.url), 'utf8');
const idsInHtml = new Set([...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]));
const sels = (st) => [typeof st.target === 'string' ? st.target : null, ...(st.see || []), ...(st.allow || [])].filter(Boolean);

test('tutorial steps are well formed and have unique ids', () => {
  assert.ok(STEPS.length >= 15); assert.equal(new Set(STEPS.map((s) => s.id)).size, STEPS.length);
  for (const s of STEPS) { assert.ok(s.title && s.text, s.id); if (s.ready) assert.equal(typeof s.ready, 'function'); if (s.allow) assert.ok(s.target, s.id + ' allows input but has no highlighted target'); }
  assert.equal(STEPS[0].modal, true); assert.equal(STEPS.at(-1).modal, true);
});
test('every selector used by a step points at an element that exists in index.html (or is generated by main.js)', () => {
  const featureKeys = new Set(Object.keys(FEATURE_LABELS)), faultKeys = new Set(Object.keys(FAULT_TYPES)), viewIds = new Set(VIEWS.map((v) => v.id));
  for (const st of STEPS) for (const sel of sels(st)) {
    const id = sel.match(/#([\w-]+)/); assert.ok(id && idsInHtml.has(id[1]) || sel.startsWith('#tut'), `${st.id}: #${id && id[1]} missing in index.html`);
    const k = sel.match(/data-k="(\w+)"/); if (k) assert.ok(featureKeys.has(k[1]), 'unknown feature ' + k[1]);
    const f = sel.match(/data-fault="(\w+)"/); if (f) assert.ok(faultKeys.has(f[1]), 'unknown fault ' + f[1]);
    const v = sel.match(/data-id="(\w+)"/); if (v) assert.ok(viewIds.has(v[1]), 'unknown view ' + v[1]);
  }
});
test('main.js generates the data attributes the tutorial selects on', () => {
  const main = readFileSync(new URL('../web/main.js', import.meta.url), 'utf8');
  assert.match(main, /dataset\.k = k/); assert.match(main, /dataset\.fault = k/); assert.match(main, /dataset\.id = v\.id/);
});
test('input gate: only the step\'s own controls (and the tutorial popover) are allowed', () => {
  const step = { allow: ['#btnPause'], keys: ['Space'] }, within = (set) => (sel) => set.has(sel);
  assert.equal(eventAllowed(step, within(new Set(['#btnPause']))), true);
  assert.equal(eventAllowed(step, within(new Set(['#btnRestart']))), false);
  assert.equal(eventAllowed(step, within(new Set(['#tut-pop']))), true, 'popover buttons always work');
  assert.equal(eventAllowed(step, within(new Set()), 'Space'), true); assert.equal(eventAllowed(step, within(new Set()), 'KeyN'), false);
  assert.equal(eventAllowed({}, within(new Set(['#map']))), false, 'read-only steps allow nothing');
});
test('steps with an expected action unlock only when it has happened', () => {
  const eng = new Engine({ fleetSize: 5, seed: 1 }), api = { state: { paused: false, speed: 2, view: 'traffic', selectedId: null, params: { wind: 3.5, demand: 3 }, engine: eng }, setView() {}, $() {} };
  const by = (id) => STEPS.find((s) => s.id === id);
  assert.equal(by('pause').ready(api), false); api.state.paused = true; assert.equal(by('pause').ready(api), true); assert.equal(by('resume').ready(api), false);
  let b = by('speed').enter(api); assert.equal(by('speed').ready(api, b), false); api.state.speed = 5; assert.equal(by('speed').ready(api, b), true);
  assert.equal(by('select').ready(api), false); api.state.selectedId = 0; assert.equal(by('select').ready(api), true);
  b = by('fault').enter(api); assert.equal(by('fault').ready(api, b), false); eng.faultRecords.push({}); assert.equal(by('fault').ready(api, b), true);
  assert.equal(by('toggle').ready(api), false); eng.setFeature('stadiumTfr', true); assert.equal(by('toggle').ready(api), true);
  assert.equal(by('stress').ready(api), false); eng.stress = true; assert.equal(by('stress').ready(api), true);
  b = by('wind').enter(api); assert.equal(by('wind').ready(api, b), false); api.state.params.wind = 9; assert.equal(by('wind').ready(api, b), true);
});
test('first-visit detection tolerates missing localStorage', () => { assert.equal(Tutorial.seen(), false); Tutorial.markSeen(); });
